#!/usr/bin/env python3
"""
Generates sailfish/sources.pri (used by sailfish/sailmc.pro) from a configured CMake build of SailMC.

The qmake project builds the same files as the CMake build, so instead of keeping two hand written
file lists in sync, the list is taken from CMake:

  # inside the Sailfish SDK build engine
  mkdir build && cd build
  sb2 -t <target> cmake <repo> -DCMAKE_EXPORT_COMPILE_COMMANDS=ON
  sb2 -t <target> make sailmc              # runs AUTOMOC, so the header lists exist
  python3 <repo>/sailfish/qmake/generate-pri.py <build dir> <repo>

Only the targets that end up in the sailmc binary are used (no unit tests).
"""
import json
import os
import re
import shlex
import sys

TARGETS = [
    "Launcher_logic", "Launcher_quazip", "Launcher_nbt++", "Launcher_classparser", "Launcher_rainbow",
    "systeminfo", "hoedown", "qrcode", "tomlc99", "Katabasis", "LocalPeer", "sailmc",
]
# generated by CMake, replaced by the files in sailfish/qmake/
GENERATED = {"BuildConfig.cpp"}


def main():
    build, repo = (os.path.abspath(p) for p in sys.argv[1:3])
    sailfish = os.path.join(repo, "sailfish")

    def rel(path):
        path = os.path.normpath(path)
        if not path.startswith(repo + os.sep):
            return None
        return "$$PWD/" + os.path.relpath(path, sailfish)

    sources, includes = {}, set()
    for entry in json.load(open(os.path.join(build, "compile_commands.json"))):
        target = re.search(r"/([^/]+)\.dir/", entry.get("output", entry["command"])).group(1)
        if target not in TARGETS:
            continue
        src = os.path.normpath(os.path.join(entry["directory"], entry["file"]))
        if os.path.basename(src) in GENERATED or not src.startswith(repo):
            continue  # moc/rcc compilation units and configured files
        sources[src] = target
        args = shlex.split(entry["command"])
        for i, arg in enumerate(args):
            inc = arg[2:] if arg.startswith("-I") else (args[i + 1] if arg == "-isystem" else None)
            if inc and rel(inc):
                includes.add(rel(inc))

    headers = set()
    for target in TARGETS:
        info = None
        for root, dirs, files in os.walk(build):
            if os.path.basename(root) == target + "_autogen.dir" and "AutogenInfo.json" in files:
                info = json.load(open(os.path.join(root, "AutogenInfo.json")))
        for header in (info or {}).get("HEADERS", []):
            if rel(header[0]):
                headers.add(rel(header[0]))

    c_sources = sorted(rel(s) for s in sources if s.endswith(".c"))
    cpp_sources = sorted(rel(s) for s in sources if not s.endswith(".c"))

    out = ["# Generated by sailfish/qmake/generate-pri.py from the CMake build - do not edit.", ""]
    out.append("INCLUDEPATH += \\")
    out += ["    %s \\" % i for i in sorted(includes)] + [""]
    out.append("SOURCES += \\")
    out += ["    %s \\" % s for s in cpp_sources + c_sources] + [""]
    out.append("HEADERS += \\")
    out += ["    %s \\" % h for h in sorted(headers)] + [""]
    path = os.path.join(sailfish, "sources.pri")
    open(path, "w").write("\n".join(out))
    print("wrote %s: %d sources, %d headers, %d include paths" % (path, len(sources), len(headers), len(includes)))


if __name__ == "__main__":
    main()
